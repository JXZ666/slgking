from dataclasses import dataclass
import unicodedata

@dataclass(frozen=True)
class HelpBlock:
    kind: str
    text: str
    detail: str = ""
    tone: str = "normal"

@dataclass(frozen=True)
class HelpSection:
    key: str
    title: str
    blocks: tuple

    @property
    def searchable_text(self):
        return "\n".join([self.title] + [b.text + " " + b.detail for b in self.blocks])

def normalize_query(text):
    return unicodedata.normalize("NFKC", str(text)).casefold().strip()

def search_sections(query, sections=None):
    tokens = normalize_query(query).split()
    return tuple(s for s in (HELP_SECTIONS if sections is None else sections)
                 if all(t in normalize_query(s.searchable_text) for t in tokens))

